#!/usr/bin/env python3
"""Fetch the latest public SEC N-PORT (NPORT-P) filing of US ETFs the xray index lacks and write config/holdings_supplements/us_nport_<date>.json.

Public EDGAR only; SEC asks for a contact in the User-Agent, so set SEC_USER_AGENT="Your Name you@example.com". Weights are % of net assets as filed
(options carry their own sign; T-bills / money-market funds are shown as cash; the rest of net assets is a stated residual row).

    SEC_USER_AGENT="Name email" python tools/build_nport_supplement.py TICKER [TICKER ...] --out config/holdings_supplements/us_nport.json
"""
from __future__ import annotations

import argparse
import gzip
import json
import os
import re
import sys
import time
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app import nport_parser as npp  # noqa: E402

_last = [0.0]


def get(url: str) -> bytes:
    ua = os.environ.get("SEC_USER_AGENT")
    if not ua:
        sys.exit("set SEC_USER_AGENT to 'Your Name your@email' (SEC fair-access policy)")
    for a in range(4):
        time.sleep(max(0.0, 0.2 - (time.time() - _last[0])))
        _last[0] = time.time()
        try:
            r = urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": ua, "Accept-Encoding": "gzip"}), timeout=120)
            b = r.read()
            return gzip.decompress(b) if r.headers.get("Content-Encoding") == "gzip" else b
        except Exception as e:  # noqa: BLE001
            print("retry", url, e, file=sys.stderr)
            time.sleep(5 * (a + 1))
    raise RuntimeError(url)


def latest_nport(sid: str, cik: int) -> tuple[str, str, bytes]:
    feed = get(f"https://www.sec.gov/cgi-bin/browse-edgar?action=getcompany&CIK={sid}&type=NPORT-P&dateb=&owner=include&count=10&output=atom").decode("utf8", "ignore")
    es = []
    for e in re.findall(r"<entry>(.*?)</entry>", feed, re.S):
        f = re.search(r"<filing-type>(.*?)</filing-type>", e).group(1)
        if f.startswith("NPORT-P"):
            es.append((re.search(r"<filing-date>(.*?)</filing-date>", e).group(1), re.search(r"<accession-number>(.*?)</accession-number>", e).group(1)))
    if not es:
        raise LookupError(f"no NPORT-P for {sid}")
    fd, acc = sorted(es, reverse=True)[0]
    url = f"https://www.sec.gov/Archives/edgar/data/{cik}/{acc.replace('-', '')}/primary_doc.xml"
    return fd, url, get(url)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("tickers", nargs="+")
    ap.add_argument("--out", type=Path, required=True)
    ap.add_argument("--accession", action="append", default=[], metavar="TICKER=CIK:ACCESSION",
                    help="for a fund missing from SEC's ticker file (e.g. PLTY=1924868:0002000324-26-005161); the filing is read directly")
    a = ap.parse_args(argv)
    mf = json.loads(get("https://www.sec.gov/files/company_tickers_mf.json"))["data"]
    by = {r[3]: r for r in mf}
    funds = {}
    direct = {}
    for spec in a.accession:
        t, rest = spec.split("=")
        cik, acc = rest.split(":")
        direct[t] = (int(cik), acc)
    for t in list(a.tickers) + [x for x in direct if x not in a.tickers]:
        if t in direct:
            cik, acc = direct[t]
            url = f"https://www.sec.gov/Archives/edgar/data/{cik}/{acc.replace('-', '')}/primary_doc.xml"
            fd, xml = "", get(url)
        elif t not in by:
            print(f"{t}: not in SEC company_tickers_mf.json (no filing yet?)")
            continue
        else:
            cik = by[t][0]  # fields: cik, seriesId, classId, symbol
            fd, url, xml = latest_nport(by[t][1], cik)
        p = npp.parse_nport(xml)
        h = npp.with_residual(npp.to_holdings(p))
        funds["US:" + t] = {"name": p["series"], "issuer": "sec", "as_of": p["as_of"], "url": url,
                            "source": f"SEC EDGAR N-PORT (NPORT-P{(" filed " + fd) if fd else ""}, period end {p['as_of']}): complete portfolio as filed",
                            "coverage": "every itemised position in the N-PORT (options, T-bills, funds, stocks) + stated remainder of net assets; weights = % of net assets",
                            "proxy": False, "net_assets_usd": p["net_assets"], "holdings": h}
        print(f"{t:6} {p['as_of']} rows={len(h)}")
    a.out.write_text(json.dumps({"description": "Generated by tools/build_nport_supplement.py from public SEC N-PORT filings", "funds": funds}, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    print("wrote", a.out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
