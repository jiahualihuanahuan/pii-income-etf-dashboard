#!/usr/bin/env python3
"""iShares 'latest-holdings.csv' (public product-page download) -> config/holdings_supplements/ishares_<date>.json for funds the xray index lacks.

    python tools/build_ishares_supplement.py --out config/holdings_supplements/ishares_premium_income.json \
        BALI=333207/ishares-u-s-large-cap-premium-income-active-etf BALQ=346870/ishares-nasdaq-premium-income-active-etf \
        BITA=350678/ishares-bitcoin-premium-income-etf
Weights are the published % of net assets; money-market / cash lines are cash, futures and options are derivatives; the rounding remainder is a stated row.
"""
from __future__ import annotations

import argparse
import csv
import io
import json
import re
import sys
import urllib.request
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))
from app import nport_parser as npp  # noqa: E402


def num(s: str) -> float:
    s = (s or "").replace(",", "").strip()
    return float(s) if s not in ("", "-") else 0.0


def parse(text: str) -> tuple[str, str, list[dict]]:
    rows = list(csv.reader(io.StringIO(text.lstrip("\ufeff"))))
    name = rows[0][0]
    m = re.search(r"([A-Z][a-z]{2} \d{2}, \d{4})", rows[1][1])
    as_of = datetime.strptime(m.group(1), "%b %d, %Y").date().isoformat()
    i = next(k for k, r in enumerate(rows) if r and r[0] == "Ticker")
    hdr = rows[i]
    out = []
    for r in rows[i + 1:]:
        if len(r) != len(hdr):
            continue
        d = dict(zip(hdr, r))
        ac, tk, nm = d["Asset Class"], d["Ticker"], d["Name"].strip()
        w = num(d["Weight (%)"])
        typ = d.get("Type", "")
        if ac in ("Money Market", "Cash", "Cash Collateral and Margins"):
            kind, aclass = "cash", "Cash"
        elif ac in ("Futures", "Other Derivatives") or typ in ("FUTURE", "OPTION"):
            kind, aclass = "derivative", "Derivative"
        elif ac == "Equity":
            kind, aclass = "security", "Equity"
        elif tk == "BTC" or nm.upper() == "BITCOIN":
            kind, aclass = "security", "Commodity"
        elif "ETF" in nm.upper() or "TRUST" in nm.upper():
            kind, aclass = "fund", "Equity"
        else:
            kind, aclass = "security", ac
        sector = d.get("Sector", "")
        out.append({"name": nm.title() if nm.isupper() and kind != "derivative" else nm, "ticker": "" if tk in ("-", "") or kind != "security" and kind != "fund" else tk,
                    "isin": "", "cusip": "", "w": w, "sector": "" if sector in ("-", "Cash and/or Derivatives") else sector,
                    "country": "" if d.get("Location", "-") == "-" else d["Location"], "asset_class": aclass, "currency": d.get("Currency", "") if kind == "cash" else "",
                    "kind": kind, "sub": None})
    return name, as_of, out


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("funds", nargs="+", help="TICKER=<productId>/<slug>")
    ap.add_argument("--out", type=Path, required=True)
    a = ap.parse_args(argv)
    funds = {}
    for spec in a.funds:
        t, path = spec.split("=")
        url = f"https://www.ishares.com/us/products/{path}/latest-holdings.csv"
        text = urllib.request.urlopen(urllib.request.Request(url, headers={"User-Agent": "Mozilla/5.0"}), timeout=60).read().decode("utf-8-sig")
        name, as_of, h = parse(text)
        h = npp.with_residual(h)
        funds["US:" + t] = {"name": name, "issuer": "ishares", "as_of": as_of, "url": url,
                            "source": f"iShares website holdings file (latest-holdings.csv) as of {as_of}: complete portfolio",
                            "coverage": "every position the iShares holdings file lists (stocks, cash/money-market, futures, written options); weights = published % of net assets",
                            "proxy": False, "holdings": h}
        print(f"{t} {as_of} rows={len(h)} sum={sum(x['w'] for x in h):.2f}")
    a.out.write_text(json.dumps({"description": "Generated by tools/build_ishares_supplement.py from the public iShares holdings CSVs", "funds": funds}, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    return 0


if __name__ == "__main__":
    sys.exit(main())
